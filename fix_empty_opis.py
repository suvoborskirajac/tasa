def make_opis_content(data):
    name = data["name"]
    latin = data["latin"]
    photos = data["photos"]
    recognize_items = "\n".join(f"<li>{item}</li>" for item in data["recognize"])
    
    html = f'''<div class="card"><h2>Препознавање</h2><ul>{recognize_items}</ul></div>'''
    
    # Gallery - only 1 photo available
    if photos:
        photo = photos[0]
        html += f'''<div class="card"><h2>Галерија</h2><div class="gallery-grid"><figure class="figure"><img alt="{name} — фотографија" decoding="async" loading="lazy" src="ptice2/{photo}"/><figcaption>Локална фотографија врсте.</figcaption></figure></div></div>'''
    
    # Voice card
    html += f'''<div class="card sky"><h2>Глас</h2><p>{data["voice"]}</p><div class="note">На терену: бележити да ли је налаз визуелан, звучан или потврђен фотографијом. Датум, станиште и број јединки су минималне теренске белешке.</div></div>'''
    
    return html


def fix_empty_opis(slug):
    path = f"{VIEWS}/{slug}.html"
    with open(path, "r", encoding="utf-8") as f:
        html = f.read()
    
    data = OPIS_CONTENT[slug]
    new_content = make_opis_content(data)
    
    # Replace empty opis section
    html = re.sub(
        r'<section class="panel active" id="opis"></section>',
        f'<section class="panel active" id="opis">{new_content}</section>',
        html, count=1
    )
    
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"  ✓ Fixed opis for {slug} ({data['name']})")


for slug in OPIS_CONTENT:
    fix_empty_opis(slug)

print("\nDone.")
